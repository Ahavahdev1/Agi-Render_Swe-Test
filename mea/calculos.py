class Matematica:
    def soma(self, a, b):
        return a + b

    def subtracao(self, a, b):
        return a - b

    def subtracao_tres_numeros(self, a, b, c):
        return a - b - c

    def subtracao_quatro_numeros(self, a, b, c, d):
        return a - b - c - d

    def subtracao_cinco_numeros(self, a, b, c, d, e):
        return a - b - c - d - e

    def subtracao_seis_numeros(self, a, b, c, d, e, f):
        return a - b - c - d - e - f

